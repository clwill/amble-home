# The cloud sign-in's HTTPS client (cloud.cpp): the CA bundle for amaran's servers. mbedtls stays
# in internal RAM on purpose (no EXTERNAL_MEM_ALLOC: it has no fallback, and Wi-Fi's WPA2 crypto uses it
# too); with SPIRAM_USE_MALLOC plain calloc already puts the big TLS buffers in PSRAM when it is there.
CLOUD_SDKCONFIG = {
    "CONFIG_MBEDTLS_CERTIFICATE_BUNDLE": True,
    "CONFIG_MBEDTLS_CERTIFICATE_BUNDLE_DEFAULT_CMN": True,
}


def _cloud_door_built() -> bool:
    # Same test write_assets_header uses for `present`: the door is in this build iff dist/ has cloud.js.
    dist = Path(__file__).resolve().parent.parent.parent / "web" / "box" / "dist"
    return (dist / "cloud.js").exists()


async def to_code(config):
    var = cg.new_Pvariable(config[CONF_ID])
    await cg.register_component(var, config)
    cg.add(var.set_allow_group(config[CONF_ALLOW_GROUP]))
    cg.add(var.set_release(config[CONF_RELEASE]))
    cg.add(var.set_dev_allowlist(config[CONF_DEV_ALLOWLIST]))
    cg.add(var.set_status_poll_ms(config[CONF_STATUS_POLL].total_milliseconds))
    if CONF_MDNS_ALIAS in config:
        cg.add(var.set_mdns_alias(config[CONF_MDNS_ALIAS]))

    # The mesh counters are created at boot, not by codegen, so their unit string
    # has to be in the firmware's unit table here. With a unit and a total-increasing
    # state class HA graphs them instead of writing every tick to the logbook (#22).
    from esphome.core.entity_helpers import register_unit_of_measurement
    cg.add_define("USE_ENTITY_UNIT_OF_MEASUREMENT")
    cg.add_define("AMBLE_UOM_MSG_IDX", register_unit_of_measurement("msg"))

    write_assets_header()
    web = cg.new_Pvariable(config[CONF_WEB_ID], var)
    await cg.register_component(web, config)

    for key, value in MESH_SDKCONFIG.items():
        esp32.add_idf_sdkconfig_option(key, value)
    if _cloud_door_built():
        cg.add_define("AMBLE_CLOUD_DOOR")
        esp32.include_builtin_idf_component("esp_http_client")  # excluded from ESPHome's IDF builds by default
        esp32.include_builtin_idf_component("esp-tls")
        for key, value in CLOUD_SDKCONFIG.items():
            esp32.add_idf_sdkconfig_option(key, value)
    # The no-patch status snoop (docs/decisions.md): wrap the mesh receive entry point.
    cg.add_build_flag("-Wl,--wrap=bt_mesh_generic_net_recv")

    # Reserve capacity in ESPHome's codegen-sized entity tables for the entities
    # created at boot from the NVS fixture table: one light, one number and one
    # button per fixture, plus the diagnostics (eight sensors, one binary sensor,
    # the Re-sync button). (The component table cannot be grown this way —
    # ESPHOME_COMPONENT_COUNT is fixed before this runs — so AmbleComponent drives
    # each LightState's lifecycle itself.)
    for _ in range(MAX_FIXTURES):
        CORE.register_platform_component("light", None)
        CORE.register_platform_component("number", None)
        CORE.register_platform_component("button", None)
    for _ in range(8):
        CORE.register_platform_component("sensor", None)
    CORE.register_platform_component("binary_sensor", None)
    CORE.register_platform_component("button", None)
