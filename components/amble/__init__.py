"""amble: amaran BLE-mesh fixtures as Home Assistant lights.

One component, declared once in YAML; fixtures are runtime data (NVS), so the
light/number/button/sensor entities are created at boot and this codegen only
reserves capacity for them."""

import gzip
from pathlib import Path

import esphome.codegen as cg
import esphome.config_validation as cv
from esphome.components import esp32
from esphome.const import CONF_ID
from esphome.core import CORE

DEPENDENCIES = ["esp32", "esp32_ble", "web_server_base"]
AUTO_LOAD = ["light", "number", "button", "sensor", "binary_sensor", "json"]
CODEOWNERS = ["@clwill"]

amble_ns = cg.esphome_ns.namespace("amble")
AmbleComponent = amble_ns.class_("AmbleComponent", cg.Component)
AmbleWebHandler = amble_ns.class_("AmbleWebHandler", cg.Component)

CONF_ALLOW_GROUP = "allow_group"
CONF_RELEASE = "release"
CONF_DEV_ALLOWLIST = "dev_allowlist"
CONF_WEB_ID = "web_id"
CONF_STATUS_POLL = "status_poll"
CONF_MDNS_ALIAS = "mdns_alias"

MAX_FIXTURES = 32

# The box's pages (web/box) and sql.js, assembled by `node web/box/build.mjs`,
# embedded gzipped. Written to assets_gen.h next to this file (gitignored) so
# web.cpp can include it; deterministic so an unchanged dist/ does not rebuild.
ASSETS = ["home.html", "edit.html", "box.js", "importer.js", "fixture-caps.json", "sql-wasm.js", "sql-wasm.wasm"]
# Emitted only when present in dist/ (the cloud door: AMBLE_CLOUD_DOOR=0 leaves cloud.js out).
OPTIONAL_ASSETS = ["cloud.js"]


def _symbol(asset: str) -> str:
    return asset.upper().replace(".", "_").replace("-", "_")


def write_assets_header() -> None:
    here = Path(__file__).resolve().parent
    dist = here.parent.parent / "web" / "box" / "dist"
    missing = [a for a in ASSETS if not (dist / a).exists()]
    if missing:
        raise cv.Invalid(f"web/box/dist is missing {', '.join(missing)}; run: node web/box/build.mjs")
    out = [
        "// Generated by components/amble/__init__.py from web/box/dist (gzip -9). Do not edit; gitignored.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
    ]
    present = ASSETS + [a for a in OPTIONAL_ASSETS if (dist / a).exists()]
    for a in OPTIONAL_ASSETS:
        if a in present:
            out.append(f"#define AMBLE_HAS_{_symbol(a)} 1")
    for a in present:
        name = "AMBLE_ASSET_" + _symbol(a)
        data = gzip.compress((dist / a).read_bytes(), compresslevel=9, mtime=0)
        out.append(f"static const uint8_t {name}[{len(data)}] = {{{','.join(str(b) for b in data)}}};")
        out.append(f"static const size_t {name}_SIZE = {len(data)};")
    text = "\n".join(out) + "\n"
    target = here / "assets_gen.h"
    if not target.exists() or target.read_text() != text:
        target.write_text(text)


def unicast_address(value):
    value = cv.hex_int(value)
    if not 0x0002 <= value <= 0x7FFF:
        raise cv.Invalid("must be a unicast mesh address (0x0002-0x7FFF)")
    return value


def validate_modes(config):
    # dev (default): spare-only allowlist, group out. release: the box's own fixture
    # table, group out. production: release + group. Nothing in between by accident.
    if config[CONF_ALLOW_GROUP] and not config[CONF_RELEASE]:
        raise cv.Invalid("allow_group: true requires release: true (production is a release build with group sends)")
    if config[CONF_RELEASE] and config[CONF_DEV_ALLOWLIST]:
        raise cv.Invalid("dev_allowlist is for dev builds only; remove it or set release: false")
    return config


CONFIG_SCHEMA = cv.Schema(
    {
        cv.GenerateID(): cv.declare_id(AmbleComponent),
        cv.GenerateID(CONF_WEB_ID): cv.declare_id(AmbleWebHandler),
        # Release builds (what strangers flash) may address any fixture in the box's
        # own table. Dev builds (the default) refuse any destination not in dev_allowlist.
        cv.Optional(CONF_RELEASE, default=False): cv.boolean,
        # Production only (Chris's studio): release semantics plus group/broadcast sends.
        cv.Optional(CONF_ALLOW_GROUP, default=False): cv.boolean,
        # Dev builds: the spare fixture's address, from secrets.yaml, never tracked.
        cv.Optional(CONF_DEV_ALLOWLIST, default=[]): cv.ensure_list(unicast_address),
        # How often each fixture is asked for its state when nothing else has, so HA
        # tracks changes made in the amaran app. Staggered per fixture; 0s disables.
        cv.Optional(CONF_STATUS_POLL, default="15s"): cv.positive_time_period_milliseconds,
        # A second mDNS name the box answers to, for homes with one box: with
        # name_add_mac_suffix the real name is amble-home-xxxxxx; this keeps
        # amble-home.local working. With two boxes up, whichever answers first wins.
        cv.Optional(CONF_MDNS_ALIAS): cv.hostname,
    }
).extend(cv.COMPONENT_SCHEMA)
CONFIG_SCHEMA = cv.All(CONFIG_SCHEMA, validate_modes)

