// Spike 2: write the KEY-BEARING header the spike component compiles in.
// Output path is gitignored (`mesh_config.h` pattern). Never prints the keys.
//   node gen-mesh-config.mjs [path/to/amaran.db]
import fs from "node:fs";
import initSqlJs from "../../web/importer/node_modules/sql.js/dist/sql-wasm.js";
import { extract, hex4 } from "../../web/importer/importer.js";

const dbPath = process.argv[2] ?? new URL("../03-importer/amaran.db", import.meta.url).pathname;
const caps = JSON.parse(fs.readFileSync(new URL("../../web/importer/fixture-caps.json", import.meta.url), "utf-8"));
const SQL = await initSqlJs();
const db = new SQL.Database(new Uint8Array(fs.readFileSync(dbPath)));
const r = extract(db, caps, { withKeys: true });
db.close();
if (!r.keys.net_key_present || !r.keys.app_key_present) throw new Error("keys missing in database");
const bytes = (hex) => hex.match(/../g).map((b) => "0x" + b).join(", ");
const target = r.fixtures.find((f) => /P60c/i.test(f.name));
if (!target) throw new Error("no P60c in the fixture table");
const out = `/* GENERATED by gen-mesh-config.mjs from a user's amaran.db. KEY-BEARING.
 * gitignored (mesh_config.h). Never commit, paste or log. */
#pragma once
#include <stdint.h>
static const uint8_t AMARAN_NET_KEY[16] = { ${bytes(r.keys.net_key)} };
static const uint8_t AMARAN_APP_KEY[16] = { ${bytes(r.keys.app_key)} };
#define AMARAN_TARGET_ADDR ${hex4(target.address)}   /* ${target.name.replace(/[^\w ]/g, "")} */
#define AMARAN_TARGET_HAS_COLOR ${target.caps.color ? 1 : 0}
`;
const outPath = new URL("./components/amble_spike2/mesh_config.h", import.meta.url).pathname;
fs.writeFileSync(outPath, out, { mode: 0o600 });
console.log(`wrote ${outPath} (keys and target address are in the header, not shown here)`);
